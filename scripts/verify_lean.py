#!/usr/bin/env python3
"""Build every project module and reject unproved or nonstandard-axiom results."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import subprocess
import os
import shutil
import sys
from datetime import datetime, timezone

FOCUS = Path(__file__).resolve().parents[1]
PROJECT = FOCUS / "verification/lean"
REPORT = FOCUS / "verification/lean_status.json"
LOG = FOCUS / "verification/lean.log"
installed = shutil.which("lake")
if installed:
    WRAPPER = Path(installed)
else:
    raise SystemExit("Install Lean v4.35.0 with elan and make lake available on PATH.")
os.environ["PATH"] = str(WRAPPER.parent) + os.pathsep + os.environ.get("PATH", "")


def lean_code_only(text: str) -> str:
    """Blank comments (including nested block comments) and string literals.

    Preserve line breaks for useful diagnostics. This is a conservative source
    guard; the actual soundness check is Lean compilation and collectAxioms.
    """
    out = list(text)
    i, depth = 0, 0
    state = "code"
    while i < len(text):
        if state == "block":
            if text.startswith("/-", i):
                out[i:i + 2] = "  "
                depth += 1
                i += 2
                continue
            if text.startswith("-/", i):
                out[i:i + 2] = "  "
                depth -= 1
                i += 2
                if depth == 0:
                    state = "code"
                continue
            if text[i] != "\n":
                out[i] = " "
        elif state == "line":
            if text[i] == "\n":
                state = "code"
            else:
                out[i] = " "
        elif state == "string":
            if text[i] == "\\" and i + 1 < len(text):
                out[i] = " "
                if text[i + 1] != "\n":
                    out[i + 1] = " "
                i += 2
                continue
            if text[i] == '"':
                state = "code"
            if text[i] != "\n":
                out[i] = " "
        elif text.startswith("/-", i):
            state, depth = "block", 1
            out[i:i + 2] = "  "
            i += 2
            continue
        elif text.startswith("--", i):
            state = "line"
            out[i:i + 2] = "  "
            i += 2
            continue
        elif text[i] == '"':
            state = "string"
            out[i] = " "
        i += 1
    return "".join(out)


AUDIT = r'''-- Generated by scripts/verify_lean.py; do not edit.
import EnvyFreeResearch
import Lean.Util.CollectAxioms

open Lean Elab Command in
run_cmd do
  let env := (← getEnv).setExporting false
  let moduleNames := env.header.moduleNames
  let mut total : Nat := 0
  for (declName, declInfo) in env.constants.toList do
    let fromProject := match env.getModuleIdxFor? declName with
      | some idx =>
        let modName := moduleNames[idx.toNat]!
        modName == `EnvyFreeResearch || modName.toString.startsWith "EnvyFreeResearch."
      | none => false
    if fromProject then
      let axioms ← collectAxioms declName
      let unexpected := axioms.filter fun a =>
        !(a == ``propext || a == ``Classical.choice || a == ``Quot.sound)
      unless unexpected.isEmpty do
        throwError m!"Unexpected axioms for {declName}: {unexpected.toList}"
      match declInfo with
      | .axiomInfo _ => throwError m!"Project axiom declaration: {declName}"
      | .thmInfo _ =>
        total := total + 1
        logInfo m!"#print axioms {declName}: {axioms.toList}"
      | _ => pure ()
  if total == 0 then
    throwError "No project theorem declarations found; verification cannot succeed vacuously."
  logInfo m!"AXIOM AUDIT PASSED: {total} theorem declarations; only propext, Classical.choice, Quot.sound allowed."
'''


def main() -> int:
    report: dict = {
        "status": "running",
        "started_at_utc": datetime.now(timezone.utc).isoformat(),
        "lean_version_expected": "4.35.0",
        "mathlib_tag": "v4.35.0",
        "allowed_axioms": ["propext", "Classical.choice", "Quot.sound"],
        "scope": "All selected .lean modules under verification/lean/EnvyFreeResearch",
    }
    REPORT.write_text(json.dumps(report, indent=2) + "\n")
    try:
        sources = sorted((PROJECT / "EnvyFreeResearch").rglob("*.lean"))
        if not sources:
            raise RuntimeError("No project Lean source modules exist yet.")
        source_hashes = {}
        authored_theorem_count = 0
        for path in sources:
            content = path.read_text()
            code = lean_code_only(content)
            match = re.search(r"(?<![\w'])\b(sorry|admit|axiom)\b(?![\w'])", code)
            if match:
                line = code[:match.start()].count("\n") + 1
                raise RuntimeError(f"Forbidden token {match.group(1)!r} at {path}:{line}")
            authored_theorem_count += len(re.findall(r"\b(?:theorem|lemma)\b", code))
            source_hashes[str(path.relative_to(PROJECT))] = hashlib.sha256(path.read_bytes()).hexdigest()
        report["source_sha256"] = source_hashes
        report["authored_theorem_declaration_count"] = authored_theorem_count
        modules = [".".join(p.relative_to(PROJECT).with_suffix("").parts) for p in sources]
        umbrella = "-- Generated by scripts/verify_lean.py; imports every project module.\n"
        umbrella += "".join(f"import {module}\n" for module in modules)
        (PROJECT / "EnvyFreeResearch.lean").write_text(umbrella)
        (PROJECT / "AxiomAudit.lean").write_text(AUDIT)
        with LOG.open("w") as log:
            for args in [["env", "lean", "--version"], ["build"], ["env", "lean", "AxiomAudit.lean"]]:
                command = [str(WRAPPER), *args]
                heading = "$ lake " + " ".join(args) + "\n"
                print(heading, end="", flush=True)
                log.write(heading)
                log.flush()
                proc = subprocess.Popen(command, cwd=PROJECT, stdout=subprocess.PIPE,
                                        stderr=subprocess.STDOUT, text=True)
                assert proc.stdout is not None
                for line in proc.stdout:
                    print(line, end="", flush=True)
                    log.write(line)
                rc = proc.wait()
                log.flush()
                if rc:
                    raise RuntimeError(f"Command failed with exit code {rc}: {' '.join(args)}")
        # Reject success if another agent changed sources during verification.
        for relpath, expected in source_hashes.items():
            if hashlib.sha256((PROJECT / relpath).read_bytes()).hexdigest() != expected:
                raise RuntimeError(f"Source changed during verification: {relpath}; rerun verification.")
        actual_sources = sorted(str(p.relative_to(PROJECT)) for p in (PROJECT / "EnvyFreeResearch").rglob("*.lean"))
        if actual_sources != sorted(source_hashes):
            raise RuntimeError("Project module set changed during verification; rerun verification.")
        report["status"] = "passed"
        report["module_count"] = len(sources)
        match = re.search(r"AXIOM AUDIT PASSED: (\d+) theorem declarations", LOG.read_text())
        if not match:
            raise RuntimeError("Axiom-audit success marker missing.")
        report["theorem_declaration_count"] = int(match.group(1))
        report["finished_at_utc"] = datetime.now(timezone.utc).isoformat()
        REPORT.write_text(json.dumps(report, indent=2) + "\n")
        print(f"Verified {len(sources)} modules; report: {REPORT}")
        return 0
    except Exception as exc:
        report["status"] = "failed"
        report["error"] = str(exc)
        report["finished_at_utc"] = datetime.now(timezone.utc).isoformat()
        REPORT.write_text(json.dumps(report, indent=2) + "\n")
        print(f"Lean verification FAILED: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
